function libraryRow(song,index) {

    return `

        <div class="library-row">

            <div class="row-number">
                ${index + 1}
            </div>

            <div class="row-image">

                <img
                    src="${song.image}"
                    alt="${song.title}"
                >

            </div>

            <div class="row-info">

                <h3>
                    ${song.title}
                </h3>

                <p>
                    ${song.artist}
                </p>

            </div>

            <div class="row-album">
                ${song.album}
            </div>

            <div class="row-time">
                ${song.duration}
            </div>

        </div>

    `;

}


/* =====================================================
   GET LIKED
===================================================== */

function getLiked() {

    return liked
        .map(
            id =>
                songs.find(
                    song =>
                        song.id === id
                )
        )
        .filter(Boolean);

}


/* =====================================================
   GET RECENT
===================================================== */

function getRecent() {

    return recent
        .map(
            id =>
                songs.find(
                    song =>
                        song.id === id
                )
        )
        .filter(Boolean);

}


/* =====================================================
   LIBRARY
===================================================== */

function renderLibrary(type) {

    const container =
        document.getElementById(
            "libraryContent"
        );

    if (type === "albums") {

        container.innerHTML =
            `<div class="album-grid">
                ${albums.map(albumCard).join("")}
            </div>`;

        return;

    }


    const list =
        type === "liked"
            ? getLiked()
            : getRecent();


    if (list.length === 0) {

        container.innerHTML = `

            <div class="empty">

                <div class="empty-icon">
                    ♡
                </div>

                <h2>
                    Nothing here yet
                </h2>

                <p>
                    Play songs and build your collection.
                </p>

            </div>

        `;

        return;

    }


    container.innerHTML = `

        <div class="library-list">

            ${list
                .map(libraryRow)
                .join("")}

        </div>

    `;

}


