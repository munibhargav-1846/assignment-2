/* =====================================================
   THEME
===================================================== */

document
    .getElementById("themeButton")
    .addEventListener(
        "click",
        () => {

            document.body.classList.toggle(
                "light"
            );

            localStorage.setItem(
                "tbTheme",
                document.body.classList.contains(
                    "light"
                )
                    ? "light"
                    : "dark"
            );

        }
    );


if (
    localStorage.getItem("tbTheme") ===
    "light"
) {

    document.body.classList.add(
        "light"
    );

}


