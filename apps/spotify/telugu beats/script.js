function searchMusic(value) {

    const query =
        value.trim().toLowerCase();

    if (!query) {

        document.getElementById(
            "searchResults"
        ).innerHTML = `

            <div class="empty">

                <div class="empty-icon">
                    ⌕
                </div>

                <h2>
                    Search for music
                </h2>

                <p>
                    Search for songs,
                    artists or albums.
                </p>

            </div>

        `;

        return;

    }


    const results =
        songs.filter(song =>

            song.title
                .toLowerCase()
                .includes(query)

            ||

            song.artist
                .toLowerCase()
                .includes(query)

            ||

            song.album
                .toLowerCase()
                .includes(query)

            ||

            song.mood
                .toLowerCase()
                .includes(query)

        );


    if (results.length === 0) {

        document.getElementById(
            "searchResults"
        ).innerHTML = `

            <div class="empty">

                <div class="empty-icon">
                    ♪
                </div>

                <h2>
                    No music found
                </h2>

                <p>
                    Try searching for another song.
                </p>

            </div>

        `;

        return;

    }


    document.getElementById(
        "searchResults"
    ).innerHTML =
        results
        .map(searchRow)
        .join("");

}


