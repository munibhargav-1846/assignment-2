/* =====================================================
   VOLUME
===================================================== */

volume.addEventListener(
    "input",
    () => {
        audio.volume = Number(volume.value) / 100;
        mute.textContent = audio.volume === 0 ? "🔇" : "🔊";
    }
);


mute.addEventListener(
    "click",
    () => {
        if (audio.volume > 0) {
            volume.dataset.old = volume.value;
            audio.volume = 0;
            volume.value = 0;
            mute.textContent = "🔇";
        } else {
            const old = Number(volume.dataset.old) || 80;
            volume.value = old;
            audio.volume = old / 100;
            mute.textContent = "🔊";
        }
    }
);


/* =====================================================
   NATIVE AUDIO PROGRESS
===================================================== */

audio.volume = Number(volume.value || 80) / 100;

audio.addEventListener("loadedmetadata", () => {
    totalTime.textContent = timeFormat(audio.duration);
    progressBar.value = 0;
});

audio.addEventListener("timeupdate", () => {
    if (!audio.duration) return;
    progressBar.value = (audio.currentTime / audio.duration) * 100;
    currentTime.textContent = timeFormat(audio.currentTime);
    totalTime.textContent = timeFormat(audio.duration);
});

audio.addEventListener("play", () => {
    mainPlay.textContent = "❚❚";
});

audio.addEventListener("pause", () => {
    mainPlay.textContent = "▶";
});

audio.addEventListener("ended", () => {
    if (repeatMode) {
        audio.currentTime = 0;
        audio.play();
    } else {
        nextSong();
    }
});

progressBar.addEventListener("input", () => {
    if (audio.duration) {
        audio.currentTime = (Number(progressBar.value) / 100) * audio.duration;
    }
});


