/* =====================================================
   PLAY SONG
===================================================== */

function playSong(id) {

    const index =
        songs.findIndex(
            song => song.id === Number(id)
        );

    if (index === -1) {
        return;
    }

    currentIndex = index;

    const song = songs[index];

    playerImage.src = song.image;
    playerTitle.textContent = song.title;
    playerArtist.textContent = song.artist;

    updateLikeButton();
    addRecent(song.id);

    // Each song has its own local, original audio track.
    audio.src = `audio/song-${song.id}.wav`;
    audio.load();

    audio.play()
        .then(() => {
            mainPlay.textContent = "❚❚";
        })
        .catch(() => {
            mainPlay.textContent = "▶";
        });

}


/* =====================================================
   PLAY / PAUSE
===================================================== */

function togglePlay() {

    if (currentIndex === -1) {
        playSong(songs[0].id);
        return;
    }

    if (audio.paused) {
        audio.play()
            .then(() => {
                mainPlay.textContent = "❚❚";
            })
            .catch(() => {});
    } else {
        audio.pause();
        mainPlay.textContent = "▶";
    }

}


/* =====================================================
   NEXT
===================================================== */

function nextSong() {

    if (songs.length === 0) {
        return;
    }

    if (shuffleMode) {

        currentIndex =
            Math.floor(
                Math.random() *
                songs.length
            );

    } else {

        currentIndex++;

        if (
            currentIndex >=
            songs.length
        ) {

            currentIndex = 0;

        }

    }

    playSong(
        songs[currentIndex].id
    );

}


/* =====================================================
   PREVIOUS
===================================================== */

function previousSong() {

    if (currentIndex <= 0) {

        currentIndex =
            songs.length - 1;

    } else {

        currentIndex--;

    }

    playSong(
        songs[currentIndex].id
    );

}


/* =====================================================
   LIKE
===================================================== */

function toggleLike() {

    if (currentIndex === -1) {

        toast(
            "Play a song first"
        );

        return;

    }

    const id =
        songs[currentIndex].id;

    if (
        liked.includes(id)
    ) {

        liked =
            liked.filter(
                songId =>
                    songId !== id
            );

        toast(
            "Removed from Liked Songs"
        );

    } else {

        liked.push(id);

        toast(
            "Added to Liked Songs ♥"
        );

    }

    saveData();

    updateLikeButton();

    renderLiked();

}


function updateLikeButton() {

    if (currentIndex === -1) {

        likeCurrent.textContent =
            "♡";

        return;

    }

    const id =
        songs[currentIndex].id;

    if (
        liked.includes(id)
    ) {

        likeCurrent.textContent =
            "♥";

        likeCurrent.classList.add(
            "liked"
        );

    } else {

        likeCurrent.textContent =
            "♡";

        likeCurrent.classList.remove(
            "liked"
        );

    }

}


/* =====================================================
   RECENT
===================================================== */

function addRecent(id) {

    recent =
        recent.filter(
            songId =>
                songId !== id
        );

    recent.unshift(id);

    recent =
        recent.slice(0,15);

    saveData();

}


